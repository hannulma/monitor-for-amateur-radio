def call_latlon(call: str):
    """Kutsu → (lat, lon) tai None. Etu- ja jälkiliitteet (OH/DL1ABC/P) käsitellään."""
    c = (call or "").upper().strip()
    if not c:
        return None
    parts = [p for p in c.split("/") if p]
    if len(parts) > 1:
        tail = [p for p in parts if p not in ("P", "M", "MM", "AM", "QRP", "A", "R", "B")]
        # lyhyt osa (≤ 3 merkkiä, ei numero lopussa) on usein maa-etuliite: OH/DL1ABC, DL1ABC/OH
        main = max(tail or parts, key=len)
        digit = [p for p in tail if re.fullmatch(r"\d", p)]
        pref = [p for p in tail if len(p) <= 4 and not re.fullmatch(r".*\d[A-Z]+", p) and not re.fullmatch(r"\d", p)]
        if digit and not pref:              # W1AW/7 → kutsualue 7
            c = re.sub(r"\d", digit[0], main, count=1)
        else:
            c = pref[0] if pref else main
    c = re.sub(r"-.*$", "", c)              # skimmerin "-#" tai SSID pois
    for rx, table in ((_US_RE, _US), (_VE_RE, _VE), (_JA_RE, _JA), (_VK_RE, _VK)):
        m = rx.match(c)
        if m and not any(c.startswith(p) for p in ("KH", "KL", "KP", "KC4", "NH", "NL", "NP", "WH", "WL", "WP", "AH", "AL", "JD1")):
            return table.get(m.group(1)) or _P.get(c[:2])
    for n in range(min(5, len(c)), 0, -1):
        if c[:n] in _P:
            hit = _P[c[:n]]
            m = _RU_RE.match(c)
            if m and hit == _P["UA"]:            # Euroopan Venäjä alueittain
                return _RU.get(m.group(1), hit)
            return hit
    return None
